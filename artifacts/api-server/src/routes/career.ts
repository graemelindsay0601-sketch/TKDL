import { Router } from "express";
import { db as rawDb } from "@workspace/db";
import { careerRequestScope, readRetryingCareerDatabase } from "../career/request-scope.ts";
import { createCareerService } from "../career/service.ts";
import { createCareerRouter } from "../career/router.ts";
import { createCareerCalendarRouter } from "../career/calendar/router.ts";
import { createCareerFinanceRouter } from "../career/finance/router.ts";
import { createCareerSportingService } from "../career/sporting/service.ts";
import { createCareerSportingRouter } from "../career/sporting/router.ts";
import { createCareerLiveMatchService } from "../career/live/service.ts";
import { createCareerLiveRouter } from "../career/live/router.ts";
import { createCareerIdentityService, createCareerIdentityRouter } from "../career/identity/service.ts";

import { createCareerFactsService } from "../career/facts/service.ts";
import { createCareerFactsRouter } from "../career/facts/router.ts";
import { createCareerRelationshipsService } from "../career/relationships/service.ts";
import { createCareerRelationshipsRouter } from "../career/relationships/router.ts";
import { createCareerGoalsService } from "../career/goals/service.ts";
import { createCareerGoalsRouter } from "../career/goals/router.ts";
import { createCareerRecognitionService } from "../career/recognition/service.ts";
import { createCareerRecognitionRouter } from "../career/recognition/router.ts";
import { createCareerLifeService } from "../career/life/service.ts";
import { createCareerLifeRouter } from "../career/life/router.ts";
import { createCareerLegacyService } from "../career/legacy/service.ts";
import { createCareerLegacyRouter } from "../career/legacy/router.ts";
import { createCareerRecordsService } from "../career/records/service.ts";
import { createCareerRecordsRouter } from "../career/records/router.ts";
import { createCareerClubService } from "../career/club/service.ts";
import { createCareerClubRouter } from "../career/club/router.ts";
import { createCareerTeamNightsService } from "../career/club/team-service.ts";
import { createCareerCountyLiveService } from "../career/club/county-live-service.ts";
import { createCareerCountyTrialService } from "../career/club/county-trial-service.ts";
import { createCareerHostingService } from "../career/hosting/service.ts";
import { createCareerHostingRouter } from "../career/hosting/router.ts";
import { createCareerStreamingService } from "../career/streaming/service.ts";
import { createCareerStreamingRouter } from "../career/streaming/router.ts";
import { createCareerRoadTripService } from "../career/roadtrip/service.ts";
import { createCareerRoadTripRouter } from "../career/roadtrip/router.ts";
import { createCareerCamLeagueService } from "../career/camleague/service.ts";
import { createCareerCamLeagueRouter } from "../career/camleague/router.ts";
import { createCareerProAmService } from "../career/proam/service.ts";
import { createCareerProAmRouter } from "../career/proam/router.ts";
import { createCareerNightsRouter } from "../career/nights-router.ts";
import { createCareerMoneyService } from "../career/money/service.ts";
import { createCareerMoneyRouter } from "../career/money/router.ts";
import { createCareerManagerService } from "../career/manager/service.ts";
import { createCareerManagerRouter } from "../career/manager/router.ts";
import { captureRetirement } from "../career/legacy/persistence.ts";
import {createCareerContentService,createCareerContentRouter} from "../career/content/service.ts";
import {createCareerTournamentService,createCareerTournamentRouter} from "../career/tournament/service.ts";

const db = readRetryingCareerDatabase(rawDb);
const saves = createCareerService(db,{onRetired:captureRetirement});
// A5 composes the Career: A3 calendar with A4 finance hooks and A5 sporting status/seeding/hooks,
// and A4 sponsorship reading A5 sporting facts. Every Career route uses this one composition.
const sporting = createCareerSportingService(db);
const available = (isAdmin: boolean) => saves.isAvailable(isAdmin);
// A6.5: live Career matches through the real scorer; results enter via A3's human-result boundary.
const live = createCareerLiveMatchService(db, sporting.calendar);
const router = Router();
router.use(careerRequestScope);
router.use(createCareerTournamentRouter(createCareerTournamentService(db,sporting.calendar),sporting.calendar,available));
router.use(createCareerContentRouter(createCareerContentService(db,sporting)));
router.use(createCareerFactsRouter(createCareerFactsService(db)));
router.use(createCareerRelationshipsRouter(createCareerRelationshipsService(db)));
router.use(createCareerGoalsRouter(createCareerGoalsService(db)));
router.use(createCareerRecognitionRouter(createCareerRecognitionService(db)));
router.use(createCareerLifeRouter(createCareerLifeService(db,sporting.calendar)));
router.use(createCareerLegacyRouter(createCareerLegacyService(db)));
router.use(createCareerRecordsRouter(createCareerRecordsService(db)));
router.use(createCareerClubRouter(createCareerClubService(db), createCareerTeamNightsService(db), createCareerCountyLiveService(db), createCareerCountyTrialService(db)));
router.use(createCareerMoneyRouter(createCareerMoneyService(db)));
router.use(createCareerHostingRouter(createCareerHostingService(db)));
router.use(createCareerStreamingRouter(createCareerStreamingService(db)));
router.use(createCareerRoadTripRouter(createCareerRoadTripService(db)));
router.use(createCareerCamLeagueRouter(createCareerCamLeagueService(db)));
router.use(createCareerProAmRouter(createCareerProAmService(db)));
router.use(createCareerNightsRouter(db));
router.use(createCareerManagerRouter(createCareerManagerService(db)));
// A6.5: Career identity endpoints + PROFILE_INCOMPLETE gate (first, so it guards sporting routes).
router.use(createCareerIdentityRouter(createCareerIdentityService(db), available));
router.use(createCareerLiveRouter(live, available));
router.use(createCareerSportingRouter(sporting, available));
router.use(createCareerFinanceRouter(sporting.finance, available));
router.use(createCareerCalendarRouter(sporting.calendar, available));
router.use(createCareerRouter(saves));
export default router;
