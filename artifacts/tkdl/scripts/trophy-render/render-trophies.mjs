#!/usr/bin/env node
/**
 * Workstream E2 (second pass) — offline physically based trophy renderer.
 * Renders scripts/trophy-render/trophies3d.mjs designs in headless Chromium
 * (WebGL 2 via SwiftShader, deterministic CPU rendering) to transparent WebP
 * files in public/assets/career-trophies/render/, plus render-manifest.json
 * with each image's engraving-plate rectangle.
 *
 *   node scripts/trophy-render/render-trophies.mjs [ids...]
 *
 * Requires three.js (build-time only, never shipped): set THREE_DIR to a three
 * package directory, or it is installed once into node_modules/.cache/trophy-render.
 * Uses Playwright's Chromium (PLAYWRIGHT_CORE / CHROMIUM_PATH env overrides).
 */
import http from "node:http"; import fs from "node:fs"; import path from "node:path"; import { execFileSync } from "node:child_process";
const HERE = import.meta.dirname, ROOT = path.resolve(HERE, "../.."), OUT = path.join(ROOT, "public/assets/career-trophies/render");
const cache = path.join(ROOT, "node_modules/.cache/trophy-render");
let THREE_DIR = process.env.THREE_DIR;
if (!THREE_DIR) { THREE_DIR = path.join(cache, "node_modules/three");
  if (!fs.existsSync(THREE_DIR)) { fs.mkdirSync(cache, { recursive: true }); execFileSync("npm", ["install", "--prefix", cache, "three@0.170.0", "--no-audit", "--no-fund"], { stdio: "inherit" }); } }
const PW = process.env.PLAYWRIGHT_CORE ?? "/opt/node-tools/node_modules/playwright-core";
const { chromium } = await import(path.join(PW, "index.mjs"));
const types = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".json": "application/json" };
const server = http.createServer((q, r) => {
  const url = decodeURIComponent(q.url.split("?")[0]);
  const p = url.startsWith("/three/") ? path.join(THREE_DIR, url.slice(7)) : path.join(HERE, url);
  if (!fs.existsSync(p) || fs.statSync(p).isDirectory()) { r.writeHead(404); return r.end(); }
  r.writeHead(200, { "content-type": types[path.extname(p)] ?? "application/octet-stream" }); fs.createReadStream(p).pipe(r);
}).listen(0);
const port = server.address().port;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? "/opt/pw-browsers/chromium", args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const designs = (await import(path.join(HERE, "designs-list.mjs"))).DESIGN_IDS;
const ids = process.argv.slice(2).length ? process.argv.slice(2) : designs;
fs.mkdirSync(OUT, { recursive: true });
const manifestPath = path.join(OUT, "render-manifest.json");
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : { version: 2, renderer: "three.js MeshPhysicalMaterial · studio PMREM · SwiftShader WebGL2", images: {} };
for (const id of ids) {
  const page = await browser.newPage({ viewport: { width: 400, height: 400 } });
  page.on("pageerror", e => console.error(id, e.message));
  const t0 = Date.now();
  await page.goto(`http://localhost:${port}/render.html?id=${id}`);
  await page.waitForFunction(() => window.__result, null, { timeout: 600000 });
  const res = await page.evaluate(() => window.__result);
  const file = `${id}.webp`, buf = Buffer.from(res.webp.split(",")[1], "base64");
  fs.writeFileSync(path.join(OUT, file), buf);
  const r4 = (n) => Math.round(n * 10000) / 10000;
  manifest.images[id] = { file, width: res.size[0], height: res.size[1], plate: { left: r4(res.plateRect.left), right: r4(res.plateRect.right), top: r4(res.plateRect.top), bottom: r4(res.plateRect.bottom) } };
  console.log(`${id}: ${(buf.length / 1024).toFixed(0)} KB in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  await page.close();
}
manifest.images = Object.fromEntries(Object.entries(manifest.images).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
// Typed copy for the app (plate rectangles drive engraving placement on each render).
const ts = path.join(ROOT, "src/features/career/trophies/manifest/render-manifest.ts");
fs.writeFileSync(ts, `/** Generated by scripts/trophy-render/render-trophies.mjs — do not edit. */\nexport const TROPHY_RENDERS = ${JSON.stringify(manifest, null, 2)} as const;\n`);
await browser.close(); server.close();
